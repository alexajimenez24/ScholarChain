#!/usr/bin/env bash
# PreToolUse hook (matchers: Claude Code Write|Edit|MultiEdit|NotebookEdit, Codex
# apply_patch|Edit|Write) - the ownership guard. Harness-neutral.
# Checks every path a file tool is about to create, change or delete against the write
# territories in docs/agents.md section 2 for the calling agent, and blocks (exit 2) a
# path outside it, naming the owner.
# Caller identity: the payload field agent_type (sent by Claude Code and by Codex for
# subagents, see the probe in docs/agents.md section 2); without it, the SCHOLARCHAIN_ROLE environment variable
# the human set when launching a role session; without that, the orchestrator.
# Shell writes do not pass through this hook; the reviewer and the pre-commit gate cover
# them. Fails open (exit 0 with a warning) if docs/agents.md cannot be parsed.
# Owner: factory-engineer (constitutional).
set -uo pipefail

payload=$(cat)
printf '%s' "$payload" | SCHOLARCHAIN_ROLE="${SCHOLARCHAIN_ROLE:-}" python3 -c '
import json, os, re, subprocess, sys

def say(msg):
    print("Blocked by guard-ownership hook: " + msg, file=sys.stderr)

try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)
ti = d.get("tool_input", {}) or {}
cwd = d.get("cwd") or os.getcwd()
try:
    root = subprocess.run(["git", "-C", cwd, "rev-parse", "--show-toplevel"],
                          capture_output=True, text=True, check=True).stdout.strip()
except Exception:
    sys.exit(0)
root = os.path.realpath(root)

# (path, kind) with kind in create, modify, delete.
targets = []
fp = ti.get("file_path") or ti.get("notebook_path")
if fp:
    full = os.path.join(cwd, fp)
    targets.append((full, "modify" if os.path.exists(full) else "create"))
patch = ti.get("command") or ti.get("patch") or ""
if isinstance(patch, list):
    patch = " ".join(map(str, patch))
kinds = {"Add File": "create", "Update File": "modify", "Delete File": "delete",
         "Move to": "create"}
for m in re.finditer(r"^\*\*\* (Add File|Update File|Delete File|Move to): (.+)$",
                     str(patch), re.M):
    full = os.path.join(cwd, m.group(2).strip())
    k = kinds[m.group(1)]
    if k == "create" and os.path.exists(full):
        k = "modify"
    targets.append((full, k))
if not targets:
    sys.exit(0)

try:
    text = open(os.path.join(root, "docs/agents.md"), encoding="utf-8").read()
    block = re.search(r"```territory\n(.*?)```", text, re.S).group(1)
    rules = [l.split() for l in block.splitlines() if l.strip() and not l.startswith("#")]
    assert rules and all(len(r) == 3 for r in rules)
except Exception:
    print("guard-ownership: cannot parse the territory block in docs/agents.md;"
          " ownership is not enforced for this call", file=sys.stderr)
    sys.exit(0)

def glob_re(g):
    out, i = "", 0
    while i < len(g):
        if g.startswith("**/", i): out += "(?:.*/)?"; i += 3
        elif g.startswith("**", i): out += ".*"; i += 2
        elif g[i] == "*": out += "[^/]*"; i += 1
        elif g[i] == "?": out += "[^/]"; i += 1
        else: out += re.escape(g[i]); i += 1
    return re.compile(out + r"\Z")

def grants(actor, rel):
    """Modes in which actor may write rel, after its own except rules."""
    if any(a == actor and m == "except" and glob_re(g).match(rel) for a, m, g in rules):
        excepted = True
    else:
        excepted = False
    modes = set()
    for a, m, g in rules:
        if a == actor and glob_re(g).match(rel):
            if m == "append" or (m in ("allow", "values") and not excepted):
                modes.add(m)
    return modes

actors = sorted({a for a, _, _ in rules})
agent = d.get("agent_type") or os.environ.get("SCHOLARCHAIN_ROLE") or "orchestrator"
for full, kind in targets:
    real = os.path.realpath(full)
    if real != root and not real.startswith(root + os.sep):
        continue                      # outside the repository: not governed here
    rel = os.path.relpath(real, root)
    owners = [a for a in actors if grants(a, rel)]
    if "generated" in owners:
        say(f"{rel} is generated by .agents/render.sh; edit its source under .agents/"
            " (factory-engineer) and re-render.")
        sys.exit(2)
    if "human" in owners or "none" in owners:
        say(f"{rel} is written only by the human (or by no one); agents never touch it.")
        sys.exit(2)
    modes = grants(agent, rel) if agent in actors else set()
    if not modes:
        who = ", ".join(owners) if owners else "no owner in docs/agents.md (a matrix gap:"\
              " the orchestrator escalates it to the human)"
        say(f"{agent} may not write {rel}; it belongs to {who}. Decline, name the owner"
            " in your report, and let the orchestrator route it.")
        sys.exit(2)
    if modes == {"append"} and kind != "create":
        say(f"{rel} is append-only for {agent}: write a new file, never edit or delete"
            " an existing one.")
        sys.exit(2)
    if modes == {"values"} and kind != "modify":
        say(f"{agent} only edits version values in {rel}; it never creates or deletes"
            " files (build-engineer owns the ledger structure).")
        sys.exit(2)
sys.exit(0)
'
